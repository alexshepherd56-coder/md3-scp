// Helper function to get LOs by week
export function getLOsByWeekId(weekId: string): LearningObjective[] {
  if (weekId === 'w1-anaesthesia') {
    return year4Week1LOs
  }
  return []
}

// Helper function to get LO groups for a week
export function getLOGroups(weekId: string): string[] {
  const los = getLOsByWeekId(weekId)
  const groups = [...new Set(los.map(lo => lo.group).filter(Boolean))] as string[]
  return groups
}
